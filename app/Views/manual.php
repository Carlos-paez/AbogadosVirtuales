<h2 id="bienvenido">Bienvenido a la Red de Apoyo Legal</h2>
<p>Esta aplicacion web conecta a <strong>abogados voluntarios</strong> con <strong>personas afectadas por la crisis en Venezuela</strong> que necesitan asistencia legal gratuita. A continuacion te explicamos como usar cada seccion del sistema.</p>

<hr>

<h2 id="pagina-de-informacion">Pagina de Informacion</h2>
<p>Al entrar a la pagina principal (seccion <strong>Informacion</strong> en el menu) encontraras una explicacion detallada de que es la Red de Apoyo Legal, como funciona, los estados de Venezuela donde operamos y las jurisdicciones legales que cubrimos.</p>
<p><strong>Como usarla:</strong> Solo navega y lee el contenido. La barra lateral te permite saltar rapidamente entre secciones.</p>

<hr>

<h2 id="registro-de-abogados">Registro de Abogados</h2>
<p>Si eres <strong>abogado</strong> y deseas sumarte como voluntario, esta seccion es para ti.</p>
<p><strong>Como registrarte:</strong></p>
<ol>
    <li>Haz clic en <strong>"Registro Abogados"</strong> en el menu.</li>
    <li>Completa todos los campos del formulario: nombre completo, correo electronico, telefono, tipo de documento, estado, jurisdiccion, especialidad y anos de experiencia.</li>
    <li>Haz clic en el boton <strong>"Registrarse"</strong>.</li>
    <li>Si el registro es exitoso, veras un mensaje de confirmacion en verde. Recibiras bienvenida al sistema.</li>
</ol>
<p><strong>Nota importante:</strong> El correo electronico debe ser unico. Si ya existe un abogado registrado con ese email, el sistema te lo indicara.</p>

<hr>

<h2 id="solicitar-ayuda">Solicitar Ayuda</h2>
<p>Si <strong>necesitas asistencia legal</strong> y resides en Venezuela, puedes solicitar ayuda a traves de este formulario.</p>
<p><strong>Como solicitar:</strong></p>
<ol>
    <li>Haz clic en <strong>"Solicitar Ayuda"</strong> en el menu.</li>
    <li>Completa tus datos: nombre, correo, telefono, estado, ciudad y prioridad de tu caso.</li>
    <li>Selecciona el <strong>tipo de ayuda</strong> que necesitas (puedes marcar varias opciones): Penal, Civil, Laboral, Migratorio, Familia, DDHH, entre otras.</li>
    <li>Escribe una descripcion de tu situacion en el campo de texto.</li>
    <li>Haz clic en <strong>"Enviar Solicitud"</strong>.</li>
</ol>
<p>Tu solicitud sera revisada y asignada a un abogado voluntario segun la ubicacion y especialidad requerida.</p>

<hr>

<h2 id="inicio-de-sesion">Inicio de Sesion</h2>
<p>Esta seccion es solo para <strong>administradores</strong> del sistema (coordinadores de la red).</p>
<p><strong>Como ingresar:</strong></p>
<ol>
    <li>Haz clic en <strong>"Ingresar"</strong> en la esquina superior derecha.</li>
    <li>Ingresa tu nombre de usuario y contrasena.</li>
    <li>Haz clic en <strong>"Iniciar Sesion"</strong>.</li>
</ol>
<p>Una vez dentro, tendras acceso a los modulos de <strong>Reportes</strong> y <strong>CRM</strong>.</p>

<hr>

<h2 id="reportes">Reportes</h2>
<p>El modulo de Reportes te permite consultar el <strong>directorio completo de abogados</strong> registrados en el sistema.</p>
<p><strong>Como usarlo:</strong></p>
<ol>
    <li>Haz clic en <strong>"Reportes"</strong> en el menu (debes haber iniciado sesion).</li>
    <li>Usa los filtros de busqueda para encontrar abogados por texto, estado o jurisdiccion.</li>
    <li>Los resultados se muestran en tarjetas agrupadas por estado.</li>
    <li>Puedes <strong>exportar</strong> el listado completo a un archivo CSV (compatible con Excel) haciendo clic en el boton correspondiente.</li>
</ol>

<hr>

<h2 id="crm">CRM - Gestion de Casos</h2>
<p>El modulo de <strong>CRM</strong> es el corazon del sistema. Permite gestionar todos los casos legales de principio a fin.</p>

<h3 id="crm-dashboard">Dashboard / Estadisticas</h3>
<p>Al entrar al CRM veras un panel con:</p>
<ul>
    <li><strong>Totales:</strong> Abogados registrados, solicitudes recibidas, casos abiertos y cerrados.</li>
    <li><strong>Barra de progreso:</strong> Porcentaje de casos resueltos.</li>
    <li><strong>Graficos:</strong> Distribucion de casos por estado y por prioridad.</li>
    <li><strong>Top abogados:</strong> Ranking de abogados con mas casos asignados.</li>
    <li><strong>Casos antiguos:</strong> Alertas para casos que llevan mas de 15 o 30 dias sin resolverse.</li>
    <li><strong>Actividad reciente:</strong> Ultimas acciones realizadas en el sistema.</li>
</ul>

<h3 id="crm-asignar">Asignar Caso</h3>
<p>Para crear y asignar un nuevo caso legal:</p>
<ol>
    <li>Ve a la pestana <strong>"Asignar Caso"</strong>.</li>
    <li>Selecciona la <strong>persona afectada</strong> del listado desplegable.</li>
    <li>Selecciona el <strong>abogado</strong> que tomara el caso.</li>
    <li>Ingresa un titulo, la prioridad y una descripcion del caso.</li>
    <li>Haz clic en <strong>"Asignar Caso"</strong>.</li>
</ol>

<h3 id="crm-lista">Lista de Casos</h3>
<p>Esta pestana muestra todos los casos registrados en una tabla. Puedes:</p>
<ul>
    <li><strong>Filtrar</strong> por texto, estado o prioridad.</li>
    <li><strong>Ver detalle</strong> de un caso haciendo clic en el ID o presionando la tecla <strong>E</strong>.</li>
    <li><strong>Cambiar estado</strong> con el boton o tecla <strong>S</strong>.</li>
    <li><strong>Cerrar</strong> un caso resuelto con <strong>C</strong>.</li>
    <li><strong>Reabrir</strong> un caso cerrado con <strong>R</strong>.</li>
    <li><strong>Eliminar</strong> un caso con <strong>X</strong>.</li>
</ul>
<p>Los casos urgentes se resaltan con un borde rojo en el lado izquierdo para identificarlos rapidamente.</p>

<h3 id="crm-detalle">Detalle del Caso</h3>
<p>Al abrir un caso veras un modal con:</p>
<ul>
    <li>Informacion completa del caso (titulo, prioridad, estado, fechas).</li>
    <li>Datos de la persona afectada y del abogado asignado.</li>
    <li><strong>Linea de tiempo (timeline):</strong> Historial completo de todas las actividades realizadas sobre el caso.</li>
    <li><strong>Comentarios:</strong> Puedes agregar comentarios que quedaran registrados en el historial.</li>
</ul>

<h3 id="crm-reporte">Reporte del CRM</h3>
<p>La pestana de reporte agrupa los casos por abogado, mostrando cuantos casos tiene cada uno y en que estado se encuentran. Puedes filtrar por estado y prioridad, y exportar los datos a CSV.</p>

<h3 id="crm-configuracion">Configuracion</h3>
<p>Desde el icono de engranaje (<strong>Configuracion</strong>) puedes cambiar tu contrasena de acceso. Solo necesitas ingresar tu contrasena actual, la nueva contrasena y confirmarla.</p>

<hr>

<h2 id="consejos-utiles">Consejos Utiles</h2>
<ul>
    <li><strong>Atajo de teclado:</strong> Presiona <strong>Esc</strong> para cerrar cualquier ventana modal.</li>
    <li><strong>Busqueda inteligente:</strong> Al escribir en los campos de busqueda, los resultados se filtran automaticamente sin necesidad de presionar Enter.</li>
    <li><strong>Exportacion:</strong> Los archivos CSV se abren correctamente en Excel y otros programas de hoja de calculo.</li>
    <li><strong>Navegacion movil:</strong> En dispositivos moviles, usa el icono de menu (tres lineas) para mostrar u ocultar las opciones de navegacion.</li>
</ul>

<hr>

<h2 id="acerca-de">Acerca de esta aplicacion</h2>
<p>La <strong>Red de Apoyo Legal</strong> fue desarrollada como una herramienta para facilitar el trabajo de los abogados voluntarios que brindan asistencia legal gratuita a las personas afectadas por la crisis humanitaria en Venezuela.</p>
<p><strong>Creada por:</strong> Carlos Paez — Estudiante de la UPTAEB (Universidad Politecnica Territorial Agroindustrial del Estado Barinas).</p>
<p><strong>Tecnologia:</strong> PHP, SQLite, HTML, CSS y JavaScript puro — sin frameworks ni dependencias externas.</p>
<p><strong>Proposito:</strong> Contribuir con la sociedad proporcionando una plataforma gratuita que conecte a profesionales del derecho con quienes mas lo necesitan en momentos dificiles.</p>

